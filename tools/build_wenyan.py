def load_catalog():
    payload = json.loads(CATALOG_PATH.read_text())
    words = payload.get("words") or []
    if len(words) != 1000:
        raise ValueError(f"expected 1000 high-frequency catalog entries, got {len(words)}")
    if len({row.get("word") for row in words}) != 1000:
        raise ValueError("duplicate high-frequency catalog words")
    return words


def parse_rows():
    rows = []
    for line in RAW.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split("||")
        if len(parts) != 8:
            raise ValueError(f"bad row ({len(parts)} fields): {line}")
        level, word, pinyin, meanings, example, translation, source, tip = parts
        meanings = [part.strip() for part in meanings.split("；") if part.strip()]
        if not meanings:
            raise ValueError(f"empty meanings: {word}")
        rows.append({
            "level": level,
            "word": word,
            "pinyin": pinyin,
            "meanings": meanings,
            "example": example,
            "translation": translation,
            "source": source,
            "tip": tip,
        })
    if len(rows) != 200:
        raise ValueError(f"expected 200 entries, got {len(rows)}")
    if len({row["word"] for row in rows}) != 200:
        raise ValueError("duplicate words")
    if sum(row["level"] == "core" for row in rows) != 120:
        raise ValueError("expected 120 core entries")
    if sum(row["level"] == "extension" for row in rows) != 80:
        raise ValueError("expected 80 extension entries")
    core_words = {row["word"] for row in rows if row["level"] == "core"}
    if core_words != set(CORE_WORDS):
        missing = sorted(set(CORE_WORDS) - core_words)
        extra = sorted(core_words - set(CORE_WORDS))
        raise ValueError(f"core list mismatch; missing={missing}, extra={extra}")
    return rows


def build_book():
    rows = parse_rows()
    curated_words = {row["word"] for row in rows}
    highfreq_rows = load_catalog()
    overlap = curated_words & {row["word"] for row in highfreq_rows}
    if overlap:
        raise ValueError(f"high-frequency catalog overlaps curated words: {sorted(overlap)}")

    units = []
